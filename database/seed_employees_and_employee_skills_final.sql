SELECT
    r.role_name,
    COUNT(*) AS employee_count
FROM employees e
JOIN roles r ON e.current_role_id = r.role_id
GROUP BY r.role_id, r.role_name
ORDER BY employee_count DESC, r.role_name;

SELECT
    CASE
        WHEN es.proficiency_level >= rs.required_level THEN 'Meets or exceeds'
        WHEN rs.required_level - es.proficiency_level = 1 THEN 'Small gap (1)'
        ELSE 'Significant gap (2+)'
    END AS gap_status,
    COUNT(*) AS requirement_count
FROM employees e
JOIN role_skills rs ON rs.role_id = e.current_role_id
JOIN employee_skills es
  ON es.employee_id = e.employee_id
 AND es.skill_id = rs.skill_id
GROUP BY gap_status
ORDER BY requirement_count DESC;

